import { readFileSync, writeFileSync } from 'node:fs';
import { engine } from './lib.mjs';
const [tpl, out] = process.argv.slice(2);
let s = readFileSync(tpl, 'utf8');
const UNPORTED = ['ai-color-palette','cream-palette','dark-glow','icon-tile-stack','italic-serif-display','repeated-section-kickers','aphoristic-cadence','broken-image','tight-leading','skipped-heading','theater-slop-phrase'];
const meta = (id) => { const r = engine.getRule(id); if (!r) throw new Error('no rule ' + id); const dom = engine.domainForRule(r);
  const sec = r.skillSection === null ? ` (catalog skillSection: none; fallback domain)` : '';
  return `- **\`${id}\`**: category **${r.category}**; domain **${dom}**${sec}; name: ${r.name}`; };
const msg = (id) => '`' + engine.getRule(id).description + '`';
const used = new Set();
s = s.replace(/\{\{meta:([\w-]+)\}\}/g, (_, id) => { used.add(id); return meta(id); });
s = s.replace(/\{\{msg:([\w-]+)\}\}/g, (_, id) => msg(id));
s = s.replace('{{unported}}', UNPORTED.map((id) => `${meta(id)}. Message: ${msg(id)}`).join('\n'));
for (const id of UNPORTED) used.add(id);
const missing = engine.allRuleIds().filter((id) => !used.has(id));
if (missing.length) throw new Error('rules not covered: ' + missing.join(' '));
if (/`/.test(engine.allRuleIds().map((id) => engine.getRule(id).description).join(''))) console.warn('WARNING: markdown-special characters in messages');
writeFileSync(out, s);
console.log('ok', engine.allRuleIds().length, 'rules');
