//! Read or write: what each command does, for Settings ▸ Tool access (C1.3,
//! `docs/design/settings-and-connect.md`).
//!
//! `run_command` and `batch` reach every command, so Tool access would be no boundary if they could
//! run what a turned-off tool does. The MCP server ([`check`]) holds each command they carry to the
//! same switches as the tools:
//! - a command that does what a tool does (`node.create` is `create_node`) is refused when that tool
//!   is off;
//! - a command that only reads is refused when every read-only tool is off, and one that changes
//!   something when every tool that makes changes is off;
//! - a command that isn't classified is refused (deny by default).
//!
//! The classification is registry metadata: a command in the undo history ([`CommandSpec::history`])
//! changes the document, so it writes; the others are listed here, [`READ`] or [`WRITE`]. A test
//! fails when a registered command is in neither list.

use super::CommandSpec;
use super::mcp_tools::TOOLS;

/// What a command does to the world.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Access {
    /// It only answers.
    Read,
    /// It changes something.
    Write,
}

