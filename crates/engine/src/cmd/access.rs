/// `spec`'s classification (`None`: unclassified).
pub fn access_of(spec: &CommandSpec) -> Option<Access> {
    if spec.history || WRITE.contains(&spec.id) {
        Some(Access::Write)
    } else if READ.contains(&spec.id) {
        Some(Access::Read)
    } else {
        None
    }
}

/// Command `id`'s classification (`None`: unclassified, or no such command).
pub fn access(id: &str) -> Option<Access> {
    super::find_command(id).and_then(access_of)
}

/// May an agent run `spec` through `run_command` or `batch` while the tools in `disabled` are off?
/// `Err` says why not.
pub fn check_spec(spec: &CommandSpec, disabled: &[String]) -> Result<(), String> {
    let id = spec.id;
    let off = |tool: &str| disabled.iter().any(|d| d == tool);
    let Some(class) = access_of(spec) else {
        return Err(format!(
            "`{id}` isn't classified as reading or changing things, so agents can't run it (Settings ▸ Tool access refuses what it can't classify)"
        ));
    };
    if let Some((_, tool)) = EQUIVALENT.iter().find(|(cmd, tool)| *cmd == id && off(tool)) {
        return Err(format!("`{id}` does what the tool `{tool}` does, and that tool is turned off in Scrim (Settings ▸ Tool access)"));
    }
    let read = class == Access::Read;
    if TOOLS.iter().filter(|t| t.2 == read).all(|t| off(t.0)) {
        let what = if read { "only reads, and every read-only tool" } else { "changes things, and every tool that makes changes" };
        return Err(format!("`{id}` {what} is turned off in Scrim (Settings ▸ Tool access)"));
    }
    Ok(())
}

/// [`check_spec`] for command `id`. An unknown id passes: the engine refuses it itself.
pub fn check(id: &str, disabled: &[String]) -> Result<(), String> {
    match super::find_command(id) {
        Some(spec) => check_spec(spec, disabled),
        None => Ok(()),
    }
}

